# RFC 3526 group 14: p = 2^2048 - 2^1984 - 1 + 2^64 * (floor(2^1918 * pi) + 124476), a safe prime
# (= 7 mod 8, so 2 is a square and generates the group of order (p - 1) / 2)
MODP_2048: int = int(
    "ffffffffffffffffc90fdaa22168c234c4c6628b80dc1cd129024e088a67cc74"
    "020bbea63b139b22514a08798e3404ddef9519b3cd3a431b302b0a6df25f1437"
    "4fe1356d6d51c245e485b576625e7ec6f44c42e9a637ed6b0bff5cb6f406b7ed"
    "ee386bfb5a899fa5ae9f24117c4b1fe649286651ece45b3dc2007cb8a163bf05"
    "98da48361c55d39a69163fa8fd24cf5f83655d23dca3ad961c62f356208552bb"
    "9ed529077096966d670c354e4abc9804f1746c08ca18217c32905e462e36ce3b"
    "e39e772c180e86039b2783a2ec07a28fb5c55df06f4c52c9de2bcbf695581718"
    "3995497cea956ae515d2261898fa051015728e5a8aacaa68ffffffffffffffff",
    16,
)


class DiffieHellman(AsymmetricSystem):
    name: ClassVar[str] = "dh"
    # The message is ciphered as is, trailing line feed included, so deciphering gives back the same file
    strips_newline: ClassVar[bool] = False

    # MY_PRIVATE_KEY:THEIR_PUBLIC_KEY, both made by -g (the ElGamal keys: same group, Y = G^X mod P)
    def __init__(self, key: str | None, block: bool, padding: str | None = None, signed: bool = False) -> None:
        super().__init__(key, block, padding, signed)
        self.secret: int | None = None
        self.prime: int = 0
        if key is None:
            return
        parts: list[str] = key.split(":")
        if len(parts) != 2:
            raise MyPgpError("invalid dh key: expected MY_PRIVATE_KEY:THEIR_PUBLIC_KEY")
        private: ElGamalKey = ElGamalKey.parse(parts[0])
        public: ElGamalKey = ElGamalKey.parse(parts[1])
        self.check_keys(private, public)
        self.prime = private.prime
        # Alice: (g^b)^a, Bob: (g^a)^b, the same g^(ab) that Eve can't get from g^a and g^b
        self.secret = modexp(public.value, private.value, private.prime)

    @staticmethod
    def check_keys(private: ElGamalKey, public: ElGamalKey) -> None:
        if (private.generator, private.prime) != (public.generator, public.prime):
            raise MyPgpError("the two dh keys must have the same generator and prime")
        if not 1 <= private.value < private.order():
            raise MyPgpError("invalid private key: X must be between 1 and (P - 1) / 2 - 1")
        # A public value outside the group of order q generated by g (1, P - 1...) would leave
        # the shared secret only a few possible values: small subgroup attack
        if not 1 < public.value < public.prime - 1 or modexp(public.value, public.order(), public.prime) != 1:
            raise MyPgpError("invalid public key: not in the group generated by G")

    # Same keys as ElGamal, which is Diffie-Hellman with a new key pair for each message
    def generate(self, first: str, second: str) -> bytes:
        return ElGamal(None, False).generate(first, second)

    # -g -r: a random private key in the standard group. Both sides must be in the same
    # group: a random prime for each would make their keys unusable together.
    def generate_random(self, bits: int | None) -> bytes:
        if bits is not None:
            raise MyPgpError("dh -g -r takes no size: the keys are in the standard 2048-bit group "
                             "(RFC 3526), use -g P X for another group")
        x: int = 1 + secrets.randbelow((MODP_2048 - 1) // 2 - 1)
        return ElGamal.make_keys(MODP_2048, x)

    # AES-256 key: SHA-256 of the shared secret (little-endian, as many bytes as P).
    # The message is then ciphered with AES in CTR mode and authenticated (-m ctr -a).
    def aes(self) -> Aes:
        if self.secret is None:
            raise MyPgpError("missing dh key")
        size: int = (self.prime.bit_length() + 7) // 8
        key: bytes = sha256(self.secret.to_bytes(size, "little"))
        return Aes(bytes_to_hex(key), False, operation="ctr", authenticated=True)

    def cipher(self, message: bytes) -> bytes:
        return self.aes().cipher(message)

    # The symmetric layer ends its output with a line feed (the one removed from stdin
    # by the other systems): here nothing was removed, so nothing is added
    def decipher(self, ciphered: bytes) -> bytes:
        return self.aes().decipher(ciphered)[:-1]
